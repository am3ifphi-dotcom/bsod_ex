/**
 * build-jp-font.mjs
 *
 * The game renders Japanese on canvas textures (the BSOD panel, plaques, steles, terminal copy).
 * Canvas text is rasterised immediately, so it cannot wait for a lazy webfont — if the machine has
 * no Japanese font installed, every string bakes into tofu boxes and the whole prop is ruined.
 *
 * This script self-hosts a subset of Noto Sans JP covering *exactly* the characters this project
 * uses, straight out of the @fontsource package. Run it after changing any Japanese copy:
 *
 *     node scripts/build-jp-font.mjs
 *
 * Output: public/fonts/*.woff2 + public/fonts/jp.css (checked in, so the build needs no network).
 */
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const pkgDir = path.join(root, 'node_modules', '@fontsource', 'noto-sans-jp');
const outDir = path.join(root, 'public', 'fonts');

if (!fs.existsSync(pkgDir)) {
  console.error('Missing @fontsource/noto-sans-jp. Run `npm install` first.');
  process.exit(1);
}

/** Every character visible in shipped copy: source, markup and the docs readers see. */
const SOURCES = ['src', 'index.html', 'README.md'];

function walk(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
      walk(p, acc);
    } else if (/\.(ts|mts|html|css|md|mjs)$/.test(entry.name)) {
      acc.push(p);
    }
  }
  return acc;
}

const files = SOURCES.flatMap((s) => {
  const p = path.join(root, s);
  if (!fs.existsSync(p)) return [];
  return fs.statSync(p).isDirectory() ? walk(p) : [p];
});

const codepoints = new Set();
// Minimum printable Latin + the glyphs canvas software inevitably touches.
for (let cp = 0x20; cp <= 0x7e; cp++) codepoints.add(cp);
for (const cp of [0x2018, 0x2019, 0x201c, 0x201d, 0x2026, 0x2014, 0x2013, 0x00d7, 0x2192, 0x2197, 0x25a1, 0x25b2, 0x25bc]) {
  codepoints.add(cp);
}
// Full hiragana + katakana coverage: dialogue lines change often, so pay the few KB once.
for (let cp = 0x3041; cp <= 0x3096; cp++) codepoints.add(cp);
for (let cp = 0x30a1; cp <= 0x30fa; cp++) codepoints.add(cp);
// The BSOD punctuation set.
for (const cp of [0x3000, 0x3001, 0x3002, 0x300c, 0x300d, 0x30fb, 0xff01, 0xff08, 0xff09, 0xff0c, 0xff1a, 0xff1b, 0xff1f, 0x3010, 0x3011]) {
  codepoints.add(cp);
}

for (const file of files) {
  const text = fs.readFileSync(file, 'utf8');
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x80) codepoints.add(cp);
  }
}

/** Parses a @fontsource aggregate stylesheet into usable subset rules. */
function parseCss(css) {
  const rules = [];
  const re = /@font-face\s*{([^}]*)}/g;
  let m;
  while ((m = re.exec(css))) {
    const body = m[1];
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim();
    if (!file || !range) continue;
    const ranges = range.split(',').map((part) => {
      const [a, b] = part.trim().replace(/^U\+/i, '').split('-');
      const lo = parseInt(a, 16);
      const hi = b ? parseInt(b, 16) : lo;
      return [lo, hi];
    });
    rules.push({ file, weight, ranges });
  }
  return rules;
}

const WEIGHTS = ['300'];
fs.mkdirSync(outDir, { recursive: true });
for (const f of fs.readdirSync(outDir)) fs.rmSync(path.join(outDir, f), { force: true });

const emitted = [];
let bytes = 0;
for (const weight of WEIGHTS) {
  const cssPath = path.join(pkgDir, `${weight}.css`);
  if (!fs.existsSync(cssPath)) {
    console.warn(`! weight ${weight} not found, skipping`);
    continue;
  }
  const rules = parseCss(fs.readFileSync(cssPath, 'utf8'));
  for (const rule of rules) {
    const hit = [...codepoints].some((cp) => rule.ranges.some(([lo, hi]) => cp >= lo && cp <= hi));
    if (!hit) continue;
    const src = path.join(pkgDir, 'files', rule.file);
    if (!fs.existsSync(src)) continue;
    const dest = path.join(outDir, rule.file);
    fs.copyFileSync(src, dest);
    bytes += fs.statSync(dest).size;
    emitted.push({
      weight,
      file: rule.file,
      range: rule.ranges
        .map(([lo, hi]) => (lo === hi ? `U+${lo.toString(16).toUpperCase()}` : `U+${lo.toString(16).toUpperCase()}-${hi.toString(16).toUpperCase()}`))
        .join(','),
    });
  }
}

const css = [
  '/* Generated by scripts/build-jp-font.mjs — do not edit by hand. */',
  '/* Self-hosted Noto Sans JP subsets covering every character this project renders. */',
  ...emitted.map(
    (e) =>
      `@font-face{font-family:'Noto Sans JP';font-style:normal;font-weight:${e.weight};font-display:block;` +
      `src:url(./${e.file}) format('woff2');unicode-range:${e.range};}`
  ),
  '',
].join('\n');
fs.writeFileSync(path.join(outDir, 'jp.css'), css);

console.log(
  `jp font: ${emitted.length} subset files, ${(bytes / 1024).toFixed(0)} KB, ` +
    `${codepoints.size} codepoints covered -> public/fonts/`
);
